// Bundles the real feasibility engine for the Vercel functions: node, CommonJS, one file. The browser-only sync layer (src/db/cloud.ts) is swapped for a no-op stub.
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const here = path.dirname(fileURLToPath(import.meta.url))
export default {
  input: path.join(here, 'entry.ts'),
  platform: 'node',
  output: { file: path.join(here, '../../api/_utils/engineBundle.cjs'), format: 'cjs', minify: false, banner: '// GENERATED by `npm run build:engine` from scripts/engine-server + src/engine + src/db. Do not edit by hand.' },
  plugins: [{
    name: 'cloud-stub',
    resolveId(source, importer) {
      if (importer && /src[\\/]db[\\/]index\.ts$/.test(importer) && source === './cloud') return path.join(here, 'cloudStub.ts')
      return null
    },
  }],
}
